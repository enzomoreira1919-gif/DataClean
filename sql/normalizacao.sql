-- CONSULTA 1: pedidos com nome do cliente.
SELECT p.pedido_id, c.nome AS cliente, p.data_pedido
FROM pedidos AS p
JOIN clientes AS c ON c.cliente_id = p.cliente_id
ORDER BY p.pedido_id;

-- CONSULTA 2: itens de cada pedido e subtotal por item.
SELECT ip.pedido_id, pr.nome AS produto, ip.quantidade,
       ip.preco_unitario,
       (ip.quantidade * ip.preco_unitario)::NUMERIC(10,2) AS subtotal
FROM itens_pedido AS ip
JOIN produtos AS pr ON pr.produto_id = ip.produto_id
ORDER BY ip.pedido_id, pr.nome;

-- CONSULTA 3: total calculado de cada pedido.
SELECT p.pedido_id, c.nome AS cliente,
       SUM(ip.quantidade * ip.preco_unitario)::NUMERIC(10,2) AS total_pedido
FROM pedidos AS p
JOIN clientes AS c ON c.cliente_id = p.cliente_id
JOIN itens_pedido AS ip ON ip.pedido_id = p.pedido_id
GROUP BY p.pedido_id, c.nome
ORDER BY p.pedido_id;

-- CONSULTA 4: produtos mais vendidos por quantidade.
SELECT pr.nome, SUM(ip.quantidade) AS unidades_vendidas
FROM itens_pedido AS ip
JOIN produtos AS pr ON pr.produto_id = ip.produto_id
GROUP BY pr.produto_id, pr.nome
ORDER BY unidades_vendidas DESC, pr.nome;

-- CONSULTA 5: conferir quantos registros há em cada tabela.
SELECT 'clientes' AS tabela, COUNT(*) AS registros FROM clientes
UNION ALL
SELECT 'pedidos', COUNT(*) FROM pedidos
UNION ALL
SELECT 'produtos', COUNT(*) FROM produtos
UNION ALL
SELECT 'itens_pedido', COUNT(*) FROM itens_pedido
ORDER BY tabela;
